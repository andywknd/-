"""Собирает английскую версию: config.en.js, game.en.js (+ перевод статичного HTML внутри game.en.js).
Запуск: python3 i18n/build.py  (после любых правок текстов в config.js / game.js / index.html)"""
import json, re, sys, os
H = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, H)
from jsstr import pieces, CYR
from segs import segments, TAG
W = os.path.join(H, '..', 'web') + '/'
keys = json.load(open(os.path.join(H, 'segs_ru.json')))
EN = {}
for m in ('en1', 'en2', 'en3'):
    EN.update(__import__(m).EN)
T = {keys[i]: v for i, v in EN.items()}
T.update(__import__('extra').EXTRA)
missing = set()
def tr_piece(t):
    out = []
    for is_tr, l, c, r in segments(t):
        if not is_tr: out.append(l); continue
        if c not in T: missing.add(c); out.append(l + c + r); continue
        out.append(l + T[c] + r)
    return ''.join(out)
def esc_for(src, a, en):
    # кавычка литерала: экранируем такие же кавычки внутри перевода
    q = src[a - 1]
    if q in "'\"": en = en.replace('\\' + q, '\x00').replace(q, '\\' + q).replace('\x00', '\\' + q)
    elif q in '`}': en = en.replace('`', '\\`')
    return en
for f in ['config.js', 'game.js']:
    src = open(W + f).read(); ps = pieces(src); out = src
    for a, b, t in reversed(ps):
        out = out[:a] + esc_for(src, a, tr_piece(t)) + out[b:]
    if f == 'game.js':
        html = open(W + 'index.html').read(); body = html[html.index('<body'):]
        body = re.sub(r'<script[\s\S]*?</script>', '', body); st = {}
        for part in TAG.split(body):
            if part.startswith('<'):
                for m in re.finditer(r'(?:aria-label|title|alt)="([^"]*[А-Яа-яЁё][^"]*)"', part): st[m.group(1)] = T.get(m.group(1))
            elif CYR.search(part): st[part.strip()] = T.get(part.strip())
        for k, v in st.items():
            if v is None: missing.add(k)
        pre = ("/* English build — generated by i18n/build.py from game.js. Do not edit by hand. */\n"
               "(function(){var M=" + json.dumps(st, ensure_ascii=False) + ";"
               "var w=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT),a=[];while(w.nextNode())a.push(w.currentNode);"
               "a.forEach(function(n){var t=n.nodeValue.trim();if(t&&M[t])n.nodeValue=n.nodeValue.replace(t,M[t]);});"
               "document.querySelectorAll('[aria-label],[alt],[title]').forEach(function(e){['aria-label','alt','title'].forEach(function(k){var v=e.getAttribute(k);if(v&&M[v])e.setAttribute(k,M[v]);});});"
               "document.title='Dig to America';})();\n")
        out = pre + out
    open(W + f.replace('.js', '.en.js'), 'w').write(out)
if missing:
    print('MISSING translations:'); [print(' ', repr(m)) for m in missing]; sys.exit(1)
left = [l for l in open(W + 'game.en.js').read().split('\n') if CYR.search(re.sub(r'//.*|/\*.*?\*/', '', l))]
print('ok; lines with Cyrillic left (comments excluded):', len(left))
for l in left[:8]: print('  ', l.strip()[:140])
